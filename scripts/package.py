#!/usr/bin/env python
"""Build the downloadable source archive.

Why the archive includes .git: the central claim of this project is that upstream
source was left untouched. The git history is the evidence for that claim — with
it, `git log -- src/` shows only upstream commits. Without it the claim rests on
trust. It costs about 5 MB.

Excluded: node_modules (rebuildable from package-lock.json), Python caches, and
the verification screenshots (regenerated by scripts/verify_demo.py).

    python scripts/package.py [output.zip]
"""

from __future__ import annotations

import hashlib
import os
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION = "0.1.0"
DEFAULT_OUT = ROOT.parent / f"turndown-audit-{VERSION}.zip"

# Directory names skipped anywhere in the tree.
#
# `lib` and `dist` hold build output. They are regenerated by `npm install`
# (through the upstream `prepare` script), and shipping them would let a stale
# bundle stand in for a build that no longer works.
SKIP_DIRS = {
    "node_modules",
    "lib",
    "dist",
    "__pycache__",
    ".pytest_cache",
    "shots",
    ".venv",
    "_probe",
    ".tmp",
    ".cache",
}
# File suffixes skipped anywhere in the tree.
SKIP_SUFFIXES = {".pyc", ".pyo", ".log", ".orig", ".rej"}


def should_skip(path: Path) -> bool:
    parts = set(path.parts)
    if parts & SKIP_DIRS:
        return True
    if path.suffix in SKIP_SUFFIXES:
        return True
    if path.name in {".DS_Store", "Thumbs.db"}:
        return True
    return False


def collect() -> list[Path]:
    files: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        here = Path(dirpath)
        # Prune in place so os.walk does not descend into skipped directories.
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            p = here / name
            rel = p.relative_to(ROOT)
            if should_skip(rel):
                continue
            files.append(p)
    return sorted(files)


def main() -> int:
    out = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_OUT
    files = collect()
    if not files:
        print("nothing to package")
        return 1

    # The archive root is a single directory so an unzip does not scatter files.
    prefix = f"turndown-audit-{VERSION}"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for f in files:
            rel = f.relative_to(ROOT).as_posix()
            zf.write(f, f"{prefix}/{rel}")

    # Verify the archive the way a user would: reopen it, check CRCs, and confirm
    # the entry points are present.
    with zipfile.ZipFile(out) as zf:
        bad = zf.testzip()
        if bad is not None:
            print(f"CRC check failed for {bad}")
            return 1
        names = zf.namelist()

    required = [
        "package.json",
        "README.md",
        "REPORT.md",
        "LICENSE",
        "NOTICE.md",
        "audit/index.mjs",
        "bin/turndown-audit.mjs",
        "scripts/run-tests.mjs",
        "demo/index.html",
    ]
    missing = [r for r in required if f"{prefix}/{r}" not in names]
    if missing:
        print("archive is missing required entries: " + ", ".join(missing))
        return 1

    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    size_mb = out.stat().st_size / (1024 * 1024)

    # The digest goes in a sidecar file rather than into the archive: the archive
    # contains REPORT.md, so a digest written there would be stale as soon as the
    # archive was rebuilt.
    sidecar = out.with_suffix(out.suffix + ".sha256")
    sidecar.write_text(f"{digest}  {out.name}\n", encoding="utf-8")

    print(f"archive   : {out}")
    print(f"entries   : {len(names)}")
    print(f"size      : {size_mb:.2f} MB")
    print(f"sha256    : {digest}")
    print(f"digest    : {sidecar.name}  (verify with `sha256sum -c`)")
    print()
    print("notable entries:")
    for r in required:
        print(f"  {prefix}/{r}")
    print()
    print("to reproduce:")
    print(f"  unzip {out.name} && cd {prefix}")
    print("  npm install        # builds lib/ through the upstream prepare script")
    print("  npm run test:audit")
    print("  npm run evidence")
    print("  npm test")
    return 0


if __name__ == "__main__":
    sys.exit(main())
